"""Hand routes for the critical areas (board-local mm). Everything else is left to route.py.

Each section adds tracks/vias to a Ctx. Coordinates for the repeated blocks (drivers, bucks) are written
relative to the block origin used in place.py.
"""
from field import F, B

NK = 0.25          # neck width out of 0.5 mm pitch QFN pads
VIA = (0.5, 0.3)
VIA_T = (0.45, 0.2)
VIA_P = (0.6, 0.3)  # power vias (+12V, motor)


class H:
    def __init__(self, ctx):
        self.c = ctx

    def net(self, padname):
        return self.c.pad(padname).net

    def P(self, padname):
        return self.c.pad(padname).pos

    def t(self, net, layer, pts, w):
        self.c.polyline(net, layer, pts, w, 'hand')

    def v(self, net, p, size=VIA):
        self.c.add_via(net, p, size[0], size[1], 'hand')


def rel(cx, cy):
    return lambda pts: [(round(cx + u, 4), round(cy + v, 4)) for u, v in pts]


# ------------------------------------------------------------------ TMC2209 blocks
def driver(h, cx, cy, U, J, Rbra, Rbrb, C5v, Cio, Cvcp, Ccp, ms1_3v3):
    R = rel(cx, cy)
    n = lambda pin: h.net(f'{U}.{pin}')
    # motor outputs (neck out of the pad, then 0.6 mm)
    h.t(n(21), F, R([(-2.45, 1.5), (-3.0, 1.5), (-3.0, 1.9)]), NK)                     # OA2 -> J pin 3
    h.t(n(21), F, R([(-3.0, 1.9), (-3.0, 6.0), (-1.5, 7.5), (-1.5, 8.5)]), 0.6)
    h.t(n(1), F, R([(2.45, 1.5), (3.0, 1.5), (3.0, 1.9)]), NK)                         # OB2 -> J pin 6
    h.t(n(1), F, R([(3.0, 1.9), (3.0, 6.0), (4.5, 7.5), (4.5, 8.5)]), 0.6)
    h.t(n(26), F, R([(0.5, 2.45), (0.5, 3.6)]), NK)                                     # OB1 -> J pin 4
    h.t(n(26), F, R([(0.5, 3.6), (0.5, 5.6)]), 0.5)
    h.t(n(26), F, R([(0.5, 5.6), (0.5, 8.5)]), 0.6)
    h.t(n(24), F, R([(-0.5, 2.45), (-0.5, 3.75)]), NK)                                  # OA1 hops to B.Cu
    h.t(n(24), F, R([(-0.5, 3.75), (-0.5, 4.5)]), 0.5)
    for p in R([(-0.5, 3.75), (-0.5, 4.5)]):
        h.v(n(24), p)
    h.t(n(24), B, R([(-0.5, 3.75), (-0.5, 5.8), (-1.1, 6.4), (-4.9, 6.4), (-5.5, 7.0), (-5.5, 8.5)]), 0.6)
    # sense resistors
    h.t(n(23), F, R([(-1.0, 2.45), (-1.0, 3.3), (-1.3, 3.6)]), NK)                     # BRA
    h.t(n(23), F, R([(-1.3, 3.6), (-1.568, 4.6)]), 0.5)
    h.t(n(27), F, R([(1.0, 2.45), (1.0, 3.3), (1.3, 3.6)]), NK)                        # BRB
    h.t(n(27), F, R([(1.3, 3.6), (1.568, 4.6)]), 0.5)
    for rr, s in ((Rbra, -1), (Rbrb, 1)):                                               # sense GND: 2 vias each
        g = h.P(f'{rr}.1')
        h.t('GND', F, [g, (cx + s * 5.75, g[1])], 0.6)
        for dv in (-0.4, 0.4):
            h.v('GND', (cx + s * 5.75, g[1] + dv))
    # VS pins: one via each into the In2 +12V island
    for s, pin in ((-1, 22), (1, 28)):
        h.t('+12V', F, R([(s * 1.5, 2.45), (s * 1.5, 2.75), (s * 2.15, 3.15)]), 0.3)
        h.v('+12V', R([(s * 2.15, 3.15)])[0])
    # GND pins into the exposed pad
    for pin, a, b in ((18, (-2.45, 0), (-1.6, 0)), (3, (2.45, 0.5), (1.6, 0.5)), (7, (2.45, -1.5), (1.6, -1.5)),
                      (13, (-1.0, -2.45), (-1.0, -1.6)), (10, (0.5, -2.45), (0.5, -1.6)), (9, (1.0, -2.45), (1.0, -1.6))):
        if n(pin) == 'GND':
            h.t('GND', F, R([a, b]), NK)
    # VCC_IO (15) -> Cio, VREF (17) via B.Cu to the Cio via (+3V3 band of In2)
    h.t('+3.3V', F, R([(-2.45, -1.5), (-3.15, -1.5), (-3.72, -2.07), (-3.72, -2.2)]), NK)
    h.t('+3.3V', F, R([(-3.72, -2.2), (-3.72, -3.0)]), 0.4)
    h.v('+3.3V', R([(-3.72, -3.0)])[0])
    h.t('+3.3V', F, R([(-2.45, -0.5), (-3.3, -0.5)]), NK)
    h.v('+3.3V', R([(-3.3, -0.5)])[0], VIA_T)
    h.t('+3.3V', B, R([(-3.3, -0.5), (-3.3, -2.58), (-3.72, -3.0)]), 0.3)
    if ms1_3v3:   # U8 pin 9 (MS1) = +3V3
        h.t('+3.3V', F, R([(1.0, -2.45), (1.0, -3.2), (0.85, -3.5)]), NK)
        h.v('+3.3V', R([(0.85, -3.5)])[0], VIA_T)
    # 5VOUT, charge pump, VCP
    h.t(n(8), F, R([(1.5, -2.45), (1.5, -3.1), (1.825, -3.425), (1.825, -3.95)]), NK)
    h.t(n(6), F, R([(2.45, -1.0), (2.95, -1.0), (3.45, -1.5), (3.92, -1.9)]), 0.2)
    h.t(n(5), F, R([(2.45, -0.5), (3.2, -0.5), (3.43, -0.73), (3.7, -0.73)]), 0.2)
    h.t(n(4), F, R([(2.45, 0.0), (3.2, 0.0), (3.43, 0.23), (3.7, 0.23)]), 0.2)
    h.t('+12V', F, R([(4.88, -1.9), (4.88, -0.95)]), 0.4)                               # VCP cap, VS side
    h.v('+12V', R([(4.88, -0.95)])[0])
    # ENN: straight to a via, routed on from B.Cu
    h.t(n(2), F, R([(2.45, 1.0), (3.3, 1.0)]), 0.2)
    h.v(n(2), R([(3.3, 1.0)])[0], VIA_T)


# ------------------------------------------------------------------ AP62300 bucks
def buck(h, cx, cy, U, L, Cin, Cbst, Rtop, Rbot, Co1, Co2):
    R = rel(cx, cy)
    sw, vin, fb, bst = h.net(f'{U}.2'), h.net(f'{U}.3'), h.net(f'{U}.4'), h.net(f'{U}.6')
    vout = h.net(f'{L}.2')
    h.t(sw, F, R([(-1.138, 0), (-1.9, 0)]), 0.6)
    h.t(sw, F, R([(-1.9, 0), (-3.3, 0)]), 0.8)
    h.t(sw, F, R([(-2.25, 0), (-2.25, -1.85), (-1.9, -2.2), (-0.48, -2.2)]), 0.4)        # SW -> BST cap, north of GND pin
    h.t(bst, F, R([(1.138, -0.95), (1.138, -1.5), (0.6, -2.04), (0.48, -2.2)]), 0.3)
    h.t('GND', F, R([(-1.138, -0.95), (0.0, -0.95)]), 0.4)                               # GND pin: via under the body
    h.v('GND', R([(0.0, -0.95)])[0], VIA_T)
    h.t(vin, F, R([(-1.138, 0.95), (-1.138, 2.6)]), 0.6)                                 # VIN -> Cin
    h.t(fb, F, R([(1.138, 0.95), (2.6, 0.95), (2.86, 0.69), (4.5, 0.69)]), 0.2)
    h.t(vout, F, R([(-9.7, 0), (-9.7, 4.85), (-7.5, 4.85)]), 0.8)                       # L -> output caps
    cg = h.P(f'{Cin}.1')                                                                 # Cin GND: two vias
    for dv in (-0.45, 0.45):
        h.v('GND', (cg[0] + 0.95, cg[1] + dv))
    h.t('GND', F, [cg, (cg[0] + 0.95, cg[1])], 0.8)
    h.t('GND', F, [(cg[0] + 0.95, cg[1] - 0.45), (cg[0] + 0.95, cg[1] + 0.45)], 0.6)   # tie both vias


# ------------------------------------------------------------------ 12 V input and feeds
def power(h):
    raw = h.net('P1.2')
    h.t(raw, F, [h.P('P1.2'), (10.7, 25.04)], 1.5)                                         # P1 -> F1
    h.t(h.net('F1.1'), F, [h.P('F1.1'), h.P('Q1.3')], 1.0)                                # F1 -> Q1 drain
    q = h.P('Q1.2')                                                                        # Q1 source: 3 vias to In2
    h.t('+12V', F, [q, (q[0], 24.6)], 0.6)
    h.t('+12V', F, [(21.6, 24.6), (23.3, 24.6)], 0.6)
    for u in (21.6, 22.44, 23.3):
        h.v('+12V', (u, 24.6), VIA_P)
    c1 = h.P('C1.1')
    # U6 input: F.Cu from C1 (+) north to Cin
    h.t('+12V', F, [c1, (41.0, 33.0), (43.725, 30.275), (43.725, 28.5)], 1.0)
    # U9 input: B.Cu from C1 (+) east, up to a via beside Cin
    h.t('+12V', B, [c1, (41.0, 41.0), (42.8, 42.8), (56.9, 42.8), (58.325, 41.375), (58.325, 38.4)], 1.0)
    h.v('+12V', (58.325, 38.4), VIA_P)
    h.t('+12V', F, [(58.325, 38.4), (58.325, 37.0)], 1.0)


# ------------------------------------------------------------------ USB
def usb(h):
    UP_P, UP_N = h.net('J6.3'), h.net('J6.2')
    D1_P, D1_N = h.net('J6.7'), h.net('J6.6')
    D2_P, D2_N = h.net('U2.4'), h.net('U2.3')
    W = 0.25
    # Pi (port 1, upstream) pair: B.Cu loop round the crystal, then up through U10 on F.Cu
    h.t(UP_P, B, [(14.5, 13.55), (13.25, 14.8), (13.25, 19.6), (13.65, 20.0), (25.0, 20.0), (25.4, 19.6),
                  (25.4, 8.3), (25.8, 7.9), (29.15, 7.9), (29.15, 8.15)], W)
    h.t(UP_N, B, [(16.5, 13.55), (17.75, 14.8), (17.75, 19.2), (18.15, 19.6), (24.6, 19.6), (25.0, 19.2),
                  (25.0, 7.9), (25.4, 7.5), (30.65, 7.5), (31.05, 7.9), (31.05, 8.15)], W)
    h.v(UP_P, (29.15, 8.15), VIA_T)
    h.v(UP_N, (31.05, 8.15), VIA_T)
    # flow-through: the line runs straight under U10 from pin 6 to pin 1 (pin 4 to pin 3)
    h.t(UP_P, F, [(29.15, 8.15), (29.15, 13.1), (29.55, 13.5), (32.735, 13.5)], W)
    h.t(UP_N, F, [(31.05, 8.15), (31.05, 12.6), (31.45, 13.0), (32.735, 13.0)], W)
    h.t('+5V', F, [(30.1, 9.462), (30.1, 8.25)], 0.3)                                      # U10 VBUS pin
    h.v('+5V', (30.1, 8.25), VIA_T)
    h.t('GND', F, [(30.1, 11.737), (30.1, 12.75)], 0.3)                                    # U10 GND pin
    h.v('GND', (30.1, 12.75), VIA_T)
    # camera (port 2, downstream 1) pair: F.Cu through U11 into hub DN1
    h.t(D1_P, F, [(14.5, 16.17), (14.5, 22.1), (15.3, 22.9), (24.1, 22.9), (25.15, 23.95), (28.9, 23.95),
                  (30.4, 22.45), (33.6, 22.45), (34.0, 22.05), (34.0, 16.765)], W)
    h.t(D1_N, F, [(16.5, 16.17), (16.5, 22.1), (16.9, 22.5), (24.45, 22.5), (24.9, 22.05), (33.1, 22.05),
                  (33.5, 21.65), (33.5, 16.765)], W)
    # downstream 2 pair: hub DN2 -> CH340
    h.t(D2_P, F, [(35.0, 16.765), (35.0, 20.6), (35.4, 21.0), (47.2, 21.0), (47.635, 20.565), (47.635, 17.475)], W)
    h.t(D2_N, F, [(34.5, 16.765), (34.5, 21.0), (34.9, 21.4), (48.5, 21.4), (48.905, 20.995), (48.905, 17.475)], W)
    # camera VBUS: B.Cu out of J6 pin 5, via up to the PTC
    vc = h.net('J6.5')
    h.t(vc, B, [(19.0, 16.17), (19.0, 18.5), (19.4, 18.9), (23.9, 18.9)], 0.4)
    h.v(vc, (23.9, 18.9))
    h.t(vc, F, [(23.9, 18.9), (23.9, 19.6)], 0.4)
    # U11 VBUS pin sits between its two flow-through lines: via under the body, between pins 5 and 2
    h.t('+5V', F, [(25.763, 23.0), (26.9, 23.0)], 0.3)
    h.v('+5V', (26.9, 23.0), VIA_T)
    # crystal and the tight west-side hub escapes
    xo, xi = h.net('Y1.3'), h.net('Y1.1')
    h.t(xo, F, [(27.65, 15.2), (27.65, 14.0), (32.735, 14.0)], 0.2)
    h.t(xo, F, [(27.65, 15.2), (26.2, 15.2)], 0.2)
    h.t(xi, F, [(29.35, 17.4), (30.85, 17.4), (30.85, 14.9), (31.25, 14.5), (32.735, 14.5)], 0.2)
    h.t(xi, F, [(29.35, 17.4), (29.35, 18.97)], 0.2)
    h.t(h.net('U2.34'), F, [(32.735, 15.0), (31.7, 15.0), (31.3, 15.4), (31.3, 18.52)], 0.2)           # PLLFILT
    h.t(h.net('U2.35'), F, [(32.735, 15.5), (32.15, 15.5), (31.75, 15.9), (31.75, 17.55), (32.45, 18.25), (32.45, 19.09)], 0.2)  # RBIAS
    h.t('+3.3V', F, [(32.735, 16.0), (32.25, 16.0), (32.25, 16.55)], 0.2)                 # VDDA36 via
    h.v('+3.3V', (32.25, 16.55), VIA_T)
    h.t('+3.3V', F, [(32.735, 12.5), (31.95, 12.5), (31.75, 12.3)], 0.2)                  # VDDA29 via
    h.v('+3.3V', (31.75, 12.3), VIA_T)
    h.t(h.net('U2.28'), F, [(32.735, 12.0), (32.3, 12.0), (32.3, 8.6), (31.9, 8.2), (31.9, 7.91)], 0.2)  # SUSP_IND strap
    # hub east side: decoupling straight onto the caps (keeps fanout vias out of the escapes)
    h.t('+3.3V', F, [(38.265, 13.5), (40.12, 13.5)], 0.25)                                 # VDD33 pin 15 -> C21
    h.t('+3.3V', F, [(38.265, 16.0), (39.3, 16.0), (40.12, 16.8)], 0.25)                   # VDDA pin 10 -> C22
    h.t('GND', F, [(38.265, 15.5), (37.2, 15.5)], 0.25)                                     # pin 11 into the EP
    h.t(h.net('U2.14'), F, [(38.265, 14.0), (39.55, 14.0), (40.12, 14.57)], 0.2)            # CRFILT -> C17


# ------------------------------------------------------------------ MCP23017 -> button connectors
def buttons(h):
    """Staircase bus on F.Cu: the leftmost destination runs on top, 0.45 mm pitch, steps down under C15/C16/C41/C42."""
    n = lambda pin: h.net(f'U1.{pin}')
    W = 0.2
    h.t(n(19), F, [(67.662, 37.15), (66.5, 37.15), (66.5, 39.75), (66.1, 40.15), (61.55, 40.15), (59.75, 41.95),
                   (41.24, 41.95), (40.84, 42.35), (40.84, 45.925)], W)                                          # SELECT
    h.t(n(25), F, [(70.5, 39.338), (70.5, 40.6), (62.0, 40.6), (60.2, 42.4), (47.52, 42.4), (47.12, 42.8),
                   (47.12, 45.925)], W)                                                                          # RETURN
    h.t(n(26), F, [(71.15, 39.338), (71.15, 41.05), (62.45, 41.05), (60.65, 42.85), (53.8, 42.85), (53.4, 43.25),
                   (53.4, 45.925)], W)                                                                           # TOP
    h.t(n(27), F, [(71.8, 39.338), (71.8, 41.5), (62.9, 41.5), (61.1, 43.3), (60.08, 43.3), (59.68, 43.7),
                   (59.68, 45.925)], W)                                                                          # BOTTOM
    h.t(n(28), F, [(72.45, 39.338), (72.45, 41.95), (66.36, 41.95), (65.96, 42.35), (65.96, 45.925)], W)        # LEFT
    h.t(n(1), F, [(73.338, 38.45), (74.3, 38.45), (74.7, 38.85), (74.7, 43.8), (74.3, 44.2), (72.64, 44.2),
                  (72.24, 44.6), (72.24, 45.925)], W)                                                            # RIGHT


def add_all(ctx):
    h = H(ctx)
    driver(h, 14.6, 38.05, 'U7', 'J1', 'R25', 'R26', 'C27', 'C3', 'C26', 'C28', False)
    driver(h, 30.0, 38.05, 'U8', 'J2', 'R27', 'R28', 'C31', 'C4', 'C29', 'C30', True)
    buck(h, 45.0, 25.5, 'U6', 'L2', 'C35', 'C36', 'R29', 'R30', 'C37', 'C38')
    buck(h, 59.6, 34.0, 'U9', 'L3', 'C39', 'C40', 'R33', 'R34', 'C41', 'C42')
    power(h)
    usb(h)
    buttons(h)
